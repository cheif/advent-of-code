private func part1(input: String) -> Int {
    let robots = input.split(whereSeparator: \.isNewline)
        .map { line in 
            let splits = line.split(separator: "p=")[0].split(separator: " v=")
            let p = splits[0].split(separator: ",").map { Int($0)! }
            let v = splits[1].split(separator: ",").map { Int($0)! }
            return (
                p: Position(x: p[0], y: p[1]),
                v: Position(x: v[0], y: v[1])
            )
        }
    let space: (x: Int, y: Int) = input.split(whereSeparator: \.isNewline).count > 15 ? (101, 103) : (11, 7)
    let simulations = (0..<100).reductions(robots) { old, _ in
        old.map { p, v in 
            return (
                p: Position(x: (p.x + v.x + space.x) % space.x, y: (p.y + v.y + space.y) % space.y),
                v: v
            )
        }
    }
    let final = simulations.last!.map(\.p)
    let xMid = (space.x) / 2
    let yMid = (space.y) / 2
    let quadrants = final
        .filter { $0.x != xMid && $0.y != yMid }
        .grouped { pos in
            let left = pos.x < xMid
            let top = pos.y < yMid
            if top {
                return left ? 0 : 1
            } else {
                return left ? 2 : 3
            }
    }

    return quadrants.values.map(\.count).reduce(1, *)
}

private func part2(input: String) -> Int {
    let robots = input.split(whereSeparator: \.isNewline)
        .map { line in 
            let splits = line.split(separator: "p=")[0].split(separator: " v=")
            let p = splits[0].split(separator: ",").map { Int($0)! }
            let v = splits[1].split(separator: ",").map { Int($0)! }
            return (
                p: Position(x: p[0], y: p[1]),
                v: Position(x: v[0], y: v[1])
            )
        }
    let space: (x: Int, y: Int) = input.split(whereSeparator: \.isNewline).count > 15 ? (101, 103) : (11, 7)
    let simulations = (0...).lazy.reductions(robots) { old, _ in
        old.map { p, v in 
            return (
                p: Position(x: (p.x + v.x + space.x) % space.x, y: (p.y + v.y + space.y) % space.y),
                v: v
            )
        }
    }
    let found = simulations.enumerated().first { _, sim in 
        let positions = sim.map(\.p)
        let horizontalLines = positions.grouped(by: \.y).values
            .flatMap { $0.sorted().chunked { $0.distance(to: $1) <= 1 }.filter { $0.count > 5 }}
        return horizontalLines.count > 5
    }
    // 17496 is incorrect
    return found?.offset ?? 0
}
